// Generates src/lib/confusables.ts from Unicode confusables.txt.
// Pinned Unicode version: 16.0.0 (UTS #39 security data, "MA" mapping).
// Usage: node scripts/gen-confusables.mjs [path/to/confusables.txt]
import { readFileSync, writeFileSync } from 'node:fs';
import { fileURLToPath } from 'node:url';

const UNICODE_VERSION = '16.0.0';
const URL_ = `https://www.unicode.org/Public/security/${UNICODE_VERSION}/confusables.txt`;
const out = fileURLToPath(new URL('../src/lib/confusables.ts', import.meta.url));

const local = process.argv[2];
const text = local ? readFileSync(local, 'utf8') : await (await fetch(URL_)).text();

const esc = (s) =>
  [...s]
    .map((ch) => {
      const cp = ch.codePointAt(0);
      if (cp >= 0x20 && cp < 0x7f && ch !== '"' && ch !== '\\') return ch;
      return cp > 0xffff
        ? '\\u{' + cp.toString(16) + '}'
        : '\\u' + cp.toString(16).padStart(4, '0');
    })
    .join('');

const entries = [];
for (const raw of text.replace(/^﻿/, '').split('\n')) {
  const line = raw.split('#')[0].trim();
  if (!line) continue;
  const [src, dst, kind] = line.split(';').map((p) => p.trim());
  if (kind !== 'MA' || !src || !dst) continue;
  const cp = parseInt(src, 16);
  const repl = String.fromCodePoint(...dst.split(/\s+/).map((h) => parseInt(h, 16)));
  entries.push([cp, repl]);
}
entries.sort((a, b) => a[0] - b[0]);

const body = entries.map(([cp, r]) => `  0x${cp.toString(16)}: "${esc(r)}",`).join('\n');
writeFileSync(
  out,
  `// GENERATED by scripts/gen-confusables.mjs from Unicode ${UNICODE_VERSION} confusables.txt. Do not edit.\n` +
    `export const UNICODE_CONFUSABLES_VERSION = '${UNICODE_VERSION}';\n` +
    `/** code point -> replacement string (UTS #39 "MA" mappings). */\n` +
    `export const CONFUSABLES: Readonly<Record<number, string>> = {\n${body}\n};\n`,
);
console.log(`wrote ${entries.length} entries to ${out}`);
